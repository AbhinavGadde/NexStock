CREATE TABLE sp_clients (
    client_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name VARCHAR2(150) NOT NULL,
    business_email VARCHAR2(255) NOT NULL,
    business_phone VARCHAR2(30),
    business_address VARCHAR2(500),
    status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,
    reviewed_by VARCHAR2(255),
    CONSTRAINT uq_sp_client_email UNIQUE (business_email),
    CONSTRAINT ck_sp_client_status CHECK (
        status IN ('PENDING','APPROVED','REJECTED','SUSPENDED')
    )
);

CREATE TABLE sp_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER,
    full_name VARCHAR2(150) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(30) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_user_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT uq_sp_user_email UNIQUE (email),
    CONSTRAINT ck_sp_user_role CHECK (
        role IN ('SUPER_ADMIN','CLIENT_ADMIN','STAFF')
    ),
    CONSTRAINT ck_sp_user_active CHECK (is_active IN (0,1))
);

CREATE INDEX ix_sp_users_client ON sp_users(client_id);

CREATE TABLE sp_categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    category_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_category_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT uq_sp_category_name UNIQUE (client_id, category_name),
    CONSTRAINT uq_sp_category_pair UNIQUE (client_id, category_id)
);

CREATE INDEX ix_sp_categories_client ON sp_categories(client_id);

CREATE TABLE sp_suppliers (
    supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    supplier_name VARCHAR2(150) NOT NULL,
    contact_name VARCHAR2(150),
    email VARCHAR2(255),
    phone VARCHAR2(30),
    address VARCHAR2(500),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_supplier_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT uq_sp_supplier_pair UNIQUE (client_id, supplier_id)
);

CREATE INDEX ix_sp_suppliers_client ON sp_suppliers(client_id);

CREATE TABLE sp_products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    category_id NUMBER,
    sku VARCHAR2(80) NOT NULL,
    product_name VARCHAR2(200) NOT NULL,
    description VARCHAR2(1000),
    unit_price NUMBER(12,2) DEFAULT 0 NOT NULL,
    quantity NUMBER(12,2) DEFAULT 0 NOT NULL,
    reorder_level NUMBER(12,2) DEFAULT 5 NOT NULL,
    unit VARCHAR2(30) DEFAULT 'pcs' NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_product_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT fk_sp_product_category FOREIGN KEY (client_id, category_id)
        REFERENCES sp_categories(client_id, category_id),
    CONSTRAINT uq_sp_product_sku UNIQUE (client_id, sku),
    CONSTRAINT ck_sp_product_price CHECK (unit_price >= 0),
    CONSTRAINT ck_sp_product_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_sp_product_reorder CHECK (reorder_level >= 0),
    CONSTRAINT ck_sp_product_active CHECK (is_active IN (0,1))
);

CREATE INDEX ix_sp_products_client ON sp_products(client_id);
CREATE INDEX ix_sp_products_name
    ON sp_products(client_id, product_name);

CREATE TABLE sp_purchase_orders (
    purchase_order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    supplier_id NUMBER NOT NULL,
    order_number VARCHAR2(80) NOT NULL,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    expected_date DATE,
    status VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    total_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
    notes VARCHAR2(1000),
    created_by NUMBER,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_po_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT fk_sp_po_supplier FOREIGN KEY (client_id, supplier_id)
        REFERENCES sp_suppliers(client_id, supplier_id),
    CONSTRAINT fk_sp_po_user FOREIGN KEY (created_by)
        REFERENCES sp_users(user_id),
    CONSTRAINT uq_sp_po_number UNIQUE (client_id, order_number),
    CONSTRAINT ck_sp_po_status CHECK (
        status IN ('DRAFT','ORDERED','PARTIALLY_RECEIVED',
                   'RECEIVED','CANCELLED')
    ),
    CONSTRAINT ck_sp_po_amount CHECK (total_amount >= 0)
);

CREATE INDEX ix_sp_po_client ON sp_purchase_orders(client_id);

CREATE TABLE sp_purchase_order_items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    purchase_order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity_ordered NUMBER(12,2) NOT NULL,
    quantity_received NUMBER(12,2) DEFAULT 0 NOT NULL,
    unit_cost NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_sp_poi_order
        FOREIGN KEY (client_id, purchase_order_id)
        REFERENCES sp_purchase_orders(client_id, purchase_order_id),
    CONSTRAINT fk_sp_poi_product
        FOREIGN KEY (client_id, product_id)
        REFERENCES sp_products(client_id, product_id),
    CONSTRAINT ck_sp_poi_ordered CHECK (quantity_ordered > 0),
    CONSTRAINT ck_sp_poi_received CHECK (
        quantity_received >= 0 AND quantity_received <= quantity_ordered
    ),
    CONSTRAINT ck_sp_poi_cost CHECK (unit_cost >= 0)
);

CREATE INDEX ix_sp_poi_order
    ON sp_purchase_order_items(client_id, purchase_order_id);

CREATE TABLE sp_stock_transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    transaction_type VARCHAR2(20) NOT NULL,
    quantity_change NUMBER(12,2) NOT NULL,
    quantity_before NUMBER(12,2) NOT NULL,
    quantity_after NUMBER(12,2) NOT NULL,
    reference_type VARCHAR2(50),
    reference_id NUMBER,
    notes VARCHAR2(1000),
    performed_by NUMBER,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_tx_product FOREIGN KEY (client_id, product_id)
        REFERENCES sp_products(client_id, product_id),
    CONSTRAINT fk_sp_tx_user FOREIGN KEY (performed_by)
        REFERENCES sp_users(user_id),
    CONSTRAINT ck_sp_tx_type CHECK (
        transaction_type IN ('OPENING','IN','OUT','ADJUSTMENT',
                             'RETURN','PURCHASE_RECEIPT')
    ),
    CONSTRAINT ck_sp_tx_change CHECK (quantity_change <> 0),
    CONSTRAINT ck_sp_tx_before CHECK (quantity_before >= 0),
    CONSTRAINT ck_sp_tx_after CHECK (quantity_after >= 0)
);

CREATE INDEX ix_sp_tx_client_date
    ON sp_stock_transactions(client_id, created_at);
CREATE INDEX ix_sp_tx_product
    ON sp_stock_transactions(client_id, product_id);

CREATE TABLE sp_client_reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id NUMBER NOT NULL,
    reviewed_by NUMBER NOT NULL,
    decision VARCHAR2(20) NOT NULL,
    comments VARCHAR2(1000),
    reviewed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sp_review_client FOREIGN KEY (client_id)
        REFERENCES sp_clients(client_id),
    CONSTRAINT fk_sp_review_user FOREIGN KEY (reviewed_by)
        REFERENCES sp_users(user_id),
    CONSTRAINT ck_sp_review_decision CHECK (
        decision IN ('APPROVED','REJECTED','SUSPENDED','REACTIVATED')
    )
);

CREATE INDEX ix_sp_review_client ON sp_client_reviews(client_id);

